function ConvertTo-YamlSingleQuoted {
  param([string]$Value)
  return "'$($Value.Replace("'", "''"))'"
}

function Add-EnumLines {
  param(
    [System.Collections.Generic.List[string]]$Lines,
    [string[]]$Values,
    [string]$Indent
  )
  foreach ($Value in $Values) {
    $Lines.Add("$Indent- $(ConvertTo-YamlSingleQuoted $Value)")
  }
}

function Assert-DescriptionLength {
  param([string[]]$Lines)

  foreach ($Line in $Lines) {
    if ($Line -match "^\s*description:\s*(.+)$") {
      $Value = $Matches[1].Trim()
      if ($Value.Length -gt 300) {
        throw "Description exceeds 300 characters: $Value"
      }
    }
  }
}

